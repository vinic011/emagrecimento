"""PostgreSQL persistence with the same small interface used by the local diary."""
from contextlib import closing
from datetime import datetime, timezone
import sqlite3
from pathlib import Path
from urllib.parse import urlsplit

import pandas as pd
import psycopg


class StorageConfigurationError(ValueError):
    pass


TABLE_COLUMNS = {
    'meals': ('id', 'day', 'meal', 'food', 'grams', 'kcal', 'source', 'created'),
    'habits': ('day', 'water', 'sleep', 'bike', 'bike_minutes', 'notes', 'fiber'),
    'measures': ('day', 'weight', 'waist', 'hip', 'notes'),
    'settings': ('key', 'value'),
}


def initialize_tables(connection, *, postgres=False):
    identity = 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' if postgres else 'INTEGER PRIMARY KEY'
    number = 'DOUBLE PRECISION' if postgres else 'REAL'
    connection.execute(f'CREATE TABLE IF NOT EXISTS meals (id {identity}, day TEXT, meal TEXT, food TEXT, grams {number}, kcal {number}, source TEXT, created TEXT)')
    connection.execute("CREATE TABLE IF NOT EXISTS habits (day TEXT PRIMARY KEY, water INTEGER DEFAULT 0, sleep INTEGER DEFAULT 0, bike INTEGER DEFAULT 0, bike_minutes INTEGER DEFAULT 0, notes TEXT DEFAULT '', fiber INTEGER DEFAULT 0)")
    connection.execute(f"CREATE TABLE IF NOT EXISTS measures (day TEXT PRIMARY KEY, weight {number}, waist {number}, hip {number}, notes TEXT DEFAULT '')")
    connection.execute('CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT)')


def read_frame(sql, connection, params=()):
    cursor = connection.execute(sql, params)
    try:
        return pd.DataFrame.from_records(cursor.fetchall(), columns=[column[0] for column in cursor.description])
    finally:
        cursor.close()


class PostgresDiary:
    """Only app-owned, parameterized SQL is accepted by this internal adapter.

    Values are always bound separately. Context managers commit or roll back,
    while closing is explicit, matching sqlite3.Connection's app usage.
    """
    remote = True

    def __init__(self, url):
        try:
            if not isinstance(url, str):
                raise ValueError
            parsed = urlsplit(url)
            if parsed.scheme not in ('postgres', 'postgresql') or not parsed.hostname:
                raise ValueError
        except (ValueError, TypeError):
            raise StorageConfigurationError('DATABASE_URL precisa ser uma URL PostgreSQL válida.') from None
        self._url = url
        self._local = parsed.hostname in ('localhost', '127.0.0.1', '::1')
        self.raw = self._open()

    def _open(self):
        options = {'connect_timeout': 15, 'prepare_threshold': None}
        if not self._local:
            # Certificate + hostname verification, also for a pooled Neon endpoint.
            options.update(sslmode='verify-full', sslrootcert='system')
        return psycopg.connect(self._url, **options)

    def execute(self, sql, params=()):
        self._prepare_transaction()
        return self.raw.execute(sql.replace('?', '%s'), params)

    def executemany(self, sql, rows):
        self._prepare_transaction()
        with self.raw.cursor() as cursor:
            cursor.executemany(sql.replace('?', '%s'), rows)

    def _prepare_transaction(self):
        if self.raw.info.transaction_status == psycopg.pq.TransactionStatus.IDLE:
            # Transaction-local settings also work with Neon's pooled endpoint.
            self.raw.execute("SET LOCAL statement_timeout='15s'")
            self.raw.execute("SET LOCAL lock_timeout='10s'")
            self.raw.execute('SET LOCAL search_path=public')

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        try:
            self.raw.rollback()
        finally:
            self.raw.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, traceback):
        if exc_type is None:
            self.commit()
        else:
            self.rollback()

    def backup(self, destination):
        # A fresh repeatable-read transaction exports one consistent snapshot.
        # The resulting SQLite file works with existing restore/export tooling.
        initialize_tables(destination)
        with self._open() as source:
            source.execute('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY')
            source.execute("SET LOCAL statement_timeout='15s'")
            source.execute('SET LOCAL search_path=public')
            for table, columns in TABLE_COLUMNS.items():
                selected = ','.join(columns)
                with source.execute(f'SELECT {selected} FROM {table}') as cursor:
                    rows = cursor.fetchall()
                placeholders = ','.join('?' for _ in columns)
                destination.executemany(f'INSERT INTO {table} ({selected}) VALUES ({placeholders})', rows)
        destination.commit()

    def save_daily_backup(self, day, payload):
        with self:
            self.execute('INSERT INTO daily_backups(day,payload,created) VALUES (?,?,?) ON CONFLICT(day) DO UPDATE SET payload=excluded.payload,created=excluded.created',
                         (day, payload, datetime.now(timezone.utc).isoformat()))


def open_postgres(url, start):
    connection = PostgresDiary(url)
    try:
        exists = connection.execute("SELECT to_regclass('public.settings')").fetchone()[0]
        if exists and connection.execute("SELECT value FROM settings WHERE key='schema_version'").fetchone() == ('1',):
            connection.commit()
            return connection
        # Serialize initial schema creation across simultaneous phone/desktop sessions.
        connection.execute('SELECT pg_advisory_xact_lock(76140260)')
        initialize_tables(connection, postgres=True)
        connection.execute('ALTER TABLE habits ADD COLUMN IF NOT EXISTS fiber INTEGER DEFAULT 0')
        connection.execute('CREATE TABLE IF NOT EXISTS daily_backups (day TEXT PRIMARY KEY, payload BYTEA NOT NULL, created TEXT NOT NULL)')
        connection.execute('INSERT INTO settings(key,value) VALUES (?,?) ON CONFLICT(key) DO NOTHING', ('start', start))
        connection.execute("INSERT INTO settings(key,value) VALUES ('schema_version','1') ON CONFLICT(key) DO UPDATE SET value=excluded.value")
        connection.commit()
        return connection
    except Exception:
        connection.close()
        raise


def import_sqlite_backup(connection, path):
    """Import into an empty remote diary; refuse to overwrite any user data."""
    if not getattr(connection, 'remote', False):
        raise ValueError('A importação exige o banco PostgreSQL de destino.')
    source_path = Path(path).resolve(strict=True)
    rows = {}
    with closing(sqlite3.connect(source_path.as_uri() + '?mode=ro', uri=True)) as source:
        if source.execute('PRAGMA integrity_check').fetchone() != ('ok',):
            raise ValueError('Backup corrompido.')
        for table, columns in TABLE_COLUMNS.items():
            rows[table] = source.execute(f'SELECT {",".join(columns)} FROM {table}').fetchall()
    with connection:
        connection.execute('LOCK TABLE meals,habits,measures,settings IN ACCESS EXCLUSIVE MODE')
        for table in ('meals', 'habits', 'measures'):
            if connection.execute(f'SELECT COUNT(*) FROM {table}').fetchone()[0]:
                raise ValueError('O banco de destino já contém registros. Use um banco novo para recuperar o backup.')
        if connection.execute("SELECT COUNT(*) FROM settings WHERE key NOT IN ('start','schema_version')").fetchone()[0]:
            raise ValueError('O destino já tem configurações pessoais. Use um banco novo.')
        connection.execute("DELETE FROM settings WHERE key='start'")
        for table, columns in TABLE_COLUMNS.items():
            data = rows[table]
            if table == 'settings':
                data = [row for row in data if row[0] != 'schema_version']
            connection.executemany(f'INSERT INTO {table} ({",".join(columns)}) VALUES ({",".join("?" for _ in columns)})', data)
        connection.execute("SELECT setval(pg_get_serial_sequence('meals','id'),COALESCE((SELECT MAX(id) FROM meals),1),(SELECT COUNT(*)>0 FROM meals))")
